import { readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { pages, site } from '../seo.config.mjs';

const root = fileURLToPath(new URL('../dist/', import.meta.url));
const start = '<!-- SEO:START (generated by scripts/sync-seo.mjs) -->';
const end = '<!-- SEO:END -->';
const blockPattern = /  <!-- SEO:START[^]*?<!-- SEO:END -->\r?\n/;
export const absolute = relative => new URL(relative, site.url).href;
const ref = id => ({ '@id': id });
const orgId = absolute('#organization');
const websiteId = absolute('#website');

export function textContent(html) {
  const entities = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ' };
  return html.replace(/<([a-z][\w-]*)\b[^>]*aria-hidden="true"[^>]*>[^]*?<\/\1>/gi, '')
    .replace(/<br\s*\/?>/gi, ' ').replace(/<[^>]*>/g, '')
    .replace(/&(#x[\da-f]+|#\d+|amp|lt|gt|quot|apos|nbsp);/gi, (_, entity) => {
      if (entity.startsWith('#')) return String.fromCodePoint(parseInt(entity.slice(entity[1].toLowerCase() === 'x' ? 2 : 1), entity[1].toLowerCase() === 'x' ? 16 : 10));
      return entities[entity.toLowerCase()];
    }).replace(/\s+/g, ' ').trim();
}

const escape = value => String(value).replace(/[&<>"']/g, char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[char]));
const required = (value, label) => {
  if (!value) throw new Error(`Missing SEO source: ${label}`);
  return value;
};
const contents = (html, tag) => [...html.matchAll(new RegExp(`<${tag}\\b[^>]*>([^]*?)<\\/${tag}>`, 'g'))].map(match => match[1]);
const section = (html, id) => required(html.match(new RegExp(`<section\\b[^>]*id="${id}"[^>]*>([^]*?)<\\/section>`))?.[1], `section #${id}`);
const articles = (html, className) => [...html.matchAll(/<article\b([^>]*)>([^]*?)<\/article>/g)]
  .filter(match => new RegExp(`class="[^"]*\\b${className}\\b`).test(match[1])).map(match => match[2]);

export function extractFAQ(html, sectionId) {
  return contents(section(html, sectionId), 'details').map(detail => ({
    '@type': 'Question',
    name: required(textContent(contents(detail, 'summary')[0] || ''), 'FAQ question'),
    acceptedAnswer: { '@type': 'Answer', text: required(contents(detail, 'p').map(textContent).join('\n\n'), 'FAQ answer') },
  }));
}

export function extractProjects(html) {
  return articles(html, 'project-card').map(card => ({
    key: required(card.match(/data-open-project="([^"]+)"/)?.[1], 'project key'),
    name: required(textContent(contents(card, 'h3')[0] || ''), 'project title'),
    description: required(textContent(contents(card, 'p').at(-1) || ''), 'project description'),
    image: absolute(required(card.match(/<img\b[^>]*src="([^"]+)"/)?.[1], 'project image')),
    imageAlt: textContent(card.match(/<img\b[^>]*alt="([^"]*)"/)?.[1] || ''),
  }));
}

function serviceItems(html, className, url) {
  return articles(html, className).map((card, index) => ({
    '@type': 'Service',
    '@id': className === 'solution-card' ? `${absolute(required(card.match(/class="contact-pill service-open" href="([^"]+)"/)?.[1], 'service page link'))}#service` : `${url}#service-${index + 1}`,
    url: className === 'solution-card' ? absolute(card.match(/class="contact-pill service-open" href="([^"]+)"/)[1]) : `${url}#formats`,
    name: required(textContent(contents(card, 'h3')[0] || ''), 'service title'),
    description: required(textContent(contents(card, 'p')[0] || ''), 'service description'),
    provider: ref(orgId), areaServed: site.areaServed,
  }));
}

function organization(home) {
  const footer = required(home.match(/<footer\b[^]*?<\/footer>/)?.[0], 'contact footer');
  const email = required(footer.match(/data-copy="([^"]+)"/)?.[1], 'email');
  const telephone = required(footer.match(/href="tel:([^"]+)"/)?.[1], 'telephone');
  const sameAs = [...new Set([...footer.matchAll(/href="(https:\/\/(?:t\.me|\bmax\.ru)\/[^" ]+)"/g)].map(match => textContent(match[1])))];
  return {
    '@type': 'Organization', '@id': orgId, name: site.name, url: site.url,
    email, telephone, sameAs, areaServed: site.areaServed,
    contactPoint: { '@type': 'ContactPoint', telephone, email, contactType: 'Обсуждение проекта', availableLanguage: 'ru', areaServed: site.areaServed },
  };
}

export function structuredData(page, html, home) {
  const url = absolute(page.path);
  const pageId = `${url}#webpage`;
  const webpage = {
    '@type': ['portfolio', 'articles'].includes(page.kind) ? 'CollectionPage' : 'WebPage', '@id': pageId,
    url, name: page.title, description: page.description, inLanguage: site.language,
    isPartOf: ref(websiteId), about: ref(orgId), publisher: ref(orgId),
    primaryImageOfPage: { '@type': 'ImageObject', url: absolute(page.image), caption: page.imageAlt },
  };
  const graph = [
    organization(home),
    { '@type': 'WebSite', '@id': websiteId, url: site.url, name: site.name, inLanguage: site.language, publisher: ref(orgId) },
    webpage,
  ];
  if (page.kind !== 'home') {
    webpage.breadcrumb = ref(`${url}#breadcrumb`);
    graph.push({ '@type': 'BreadcrumbList', '@id': `${url}#breadcrumb`, itemListElement: [
      { '@type': 'ListItem', position: 1, name: 'Главная', item: site.url },
      { '@type': 'ListItem', position: 2, name: page.name, item: url },
    ] });
  }
  if (page.faqSection) {
    const faqId = `${url}#faq`;
    webpage.hasPart = [ref(faqId)];
    graph.push({ '@type': 'FAQPage', '@id': faqId, url: `${url}#${page.faqSection}`, inLanguage: site.language, isPartOf: ref(pageId), mainEntity: extractFAQ(html, page.faqSection) });
  }
  if (page.projectSection) {
    const projects = extractProjects(html);
    section(html, page.projectSection);
    const projectList = {
      '@type': 'ItemList', '@id': `${url}#project-list`, name: 'Проекты студии InterDIZ',
      url: `${url}#${page.projectSection}`, numberOfItems: projects.length,
      itemListElement: projects.map((project, index) => ({
        '@type': 'ListItem', position: index + 1,
        item: { '@type': 'CreativeWork', '@id': absolute(`portfolio.html#project-${project.key}`), name: project.name, description: project.description, image: project.image, creator: ref(orgId) },
      })),
    };
    required(projects.length, 'project cards');
    webpage.mentions = [ref(projectList['@id'])];
    graph.push(projectList);
    if (page.kind === 'portfolio') webpage.mainEntity = ref(projectList['@id']);
  }
  if (page.kind === 'home' || page.kind === 'service') {
    const services = serviceItems(html, page.kind === 'home' ? 'solution-card' : 'service-format', url);
    required(services.length, 'services');
    const catalogId = `${url}#services`;
    const catalog = { '@type': 'OfferCatalog', '@id': catalogId, name: page.kind === 'home' ? 'Услуги InterDIZ' : page.catalogName, itemListElement: services.map(service => ({ '@type': 'Offer', itemOffered: service })) };
    graph.push(catalog);
    if (page.kind === 'home') {
      graph[0].hasOfferCatalog = ref(catalogId);
      webpage.mainEntity = ref(orgId);
    } else {
      const serviceId = `${url}#service`;
      webpage.mainEntity = ref(serviceId);
      graph.push({ '@type': 'Service', '@id': serviceId, url, name: page.name, serviceType: page.serviceType || page.name, description: textContent(required(html.match(/<p class="hero-description">([^]*?)<\/p>/)?.[1], 'service introduction')), provider: ref(orgId), areaServed: site.areaServed, hasOfferCatalog: ref(catalogId), mainEntityOfPage: ref(pageId) });
    }
  }
  return { '@context': 'https://schema.org', '@graph': graph };
}

export function renderHead(page, html, home) {
  const url = absolute(page.path);
  const meta = (attribute, key, value) => `  <meta ${attribute}="${key}" content="${escape(value)}">`;
  const graph = JSON.stringify(structuredData(page, html, home), null, 2).replace(/</g, '\\u003c');
  return [
    `  ${start}`, `  <title>${escape(page.title)}</title>`, meta('name', 'description', page.description),
    `  <link rel="canonical" href="${escape(url)}">`,
    meta('name', 'robots', 'index, follow, max-image-preview:large, max-snippet:-1, max-video-preview:-1'),
    meta('property', 'og:type', 'website'), meta('property', 'og:site_name', site.name),
    meta('property', 'og:locale', site.locale), meta('property', 'og:url', url),
    meta('property', 'og:title', page.title), meta('property', 'og:description', page.description),
    meta('property', 'og:image', absolute(page.image)), meta('property', 'og:image:type', page.image.endsWith('.png') ? 'image/png' : 'image/webp'), meta('property', 'og:image:alt', page.imageAlt),
    meta('name', 'twitter:card', 'summary_large_image'), meta('name', 'twitter:title', page.title),
    meta('name', 'twitter:description', page.description), meta('name', 'twitter:image', absolute(page.image)), meta('name', 'twitter:image:alt', page.imageAlt),
    '  <link rel="preload" href="./assets/inter-cyrillic.woff2" as="font" type="font/woff2" crossorigin>',
    '  <link rel="preload" href="./assets/inter-latin.woff2" as="font" type="font/woff2" crossorigin>',
    `  <script type="application/ld+json">\n${graph}\n  </script>`, `  ${end}`, '',
  ].join('\n');
}

export async function syncSEO({ check = false } = {}) {
  const origin = new URL(site.url);
  if (origin.protocol !== 'https:' || origin.pathname !== '/' || origin.search || origin.hash || origin.username || origin.password) throw new Error('site.url must be an HTTPS origin ending in /.');
  const allHTML = (await readdir(root, { recursive: true })).filter(file => file.endsWith('.html')).map(file => file.split(path.sep).join('/')).sort();
  if (JSON.stringify(allHTML) !== JSON.stringify(pages.map(page => page.file).sort())) throw new Error('Register every public HTML page in seo.config.mjs.');
  const home = await readFile(path.join(root, 'index.html'), 'utf8');
  const outputs = new Map();
  const sitemapPages = [];
  for (const page of pages) {
    const html = await readFile(path.join(root, page.file), 'utf8');
    const head = required(html.match(/<head>[^]*?<\/head>/)?.[0], `${page.file} head`);
    const cleanHead = head.replace(blockPattern, '').replace(/  <title\b[^]*?<\/title>\r?\n/g, '').replace(/  <meta name="description"[^>]*>\r?\n/g, '');
    outputs.set(page.file, html.replace(head, cleanHead.replace('</head>', `${renderHead(page, html, home)}</head>`)));
    const images = extractProjects(html).map(project => `    <image:image><image:loc>${escape(project.image)}</image:loc></image:image>`);
    sitemapPages.push(`  <url>\n    <loc>${escape(absolute(page.path))}</loc>\n${[...new Set(images)].join('\n')}\n  </url>`);
  }
  outputs.set('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">\n${sitemapPages.join('\n')}\n</urlset>\n`);
  // Do not disallow query strings: crawlers must be able to read their canonical.
  // category changes the visible selection; only inert theme/topic parameters are cleaned.
  outputs.set('robots.txt', `User-agent: *\nAllow: /\nDisallow: /AGENTS.md\n\n# Yandex: theme and retired topic do not change the page content.\nClean-param: theme&topic /\n\nSitemap: ${absolute('sitemap.xml')}\n`);
  const organizationData = organization(home);
  outputs.set('llms.txt', `# ${site.name}\n\n> ${pages[0].description}\n\nЯзык: русский. География услуг: Россия. Основной сайт: ${site.url}\n\n## Страницы\n\n${pages.map(page => `- [${page.name}](${absolute(page.path)}): ${page.description}`).join('\n')}\n\n## Контакты\n\n- Email: ${organizationData.email}\n- Телефон: ${organizationData.telephone}\n${organizationData.sameAs.map(url => `- ${url}`).join('\n')}\n\n## Источники\n\n- [Вопросы о работе со студией](${absolute('#approach')})\n- [Вопросы о разработке сайтов](${absolute('web-development.html#questions')})\n- [Контакты студии](${absolute('#contact')})\n- [Карта сайта](${absolute('sitemap.xml')})\n\nУсловия, состав работ, стоимость и сроки согласуются для конкретного проекта. Актуальные описания услуг, проектов и ответы находятся на соответствующих HTML-страницах.\n`);
  const changed = [];
  for (const [file, content] of outputs) {
    const filename = path.join(root, file);
    const previous = await readFile(filename, 'utf8').catch(error => { if (error.code === 'ENOENT') return ''; throw error; });
    // Git may check out CRLF on Windows; line endings do not make metadata stale.
    if (previous.replace(/\r\n/g, '\n') === content.replace(/\r\n/g, '\n')) continue;
    changed.push(file);
    if (!check) await writeFile(filename, content);
  }
  if (check && changed.length) throw new Error(`SEO files are stale. Run npm run sync:seo: ${changed.join(', ')}`);
  return changed;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const changed = await syncSEO({ check });
  console.log(check ? `SEO is up to date (${pages.length} pages).` : `SEO synchronized: ${changed.join(', ') || 'no changes'}.`);
}
